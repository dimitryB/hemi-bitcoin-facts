/**
 * Writes `src/abi/<Contract>.ts` from forge's build output, so the SDK carries the exact ABI and bytecode of
 * the contracts it talks to (and can place the runtime by state override when a contract is not deployed).
 *
 *   cd contracts && forge build && cd ../sdk && npm run gen:abi
 *
 * The test suite re-renders each module from contracts/out and fails if the committed file differs.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const CONTRACTS_OUT = resolve(HERE, "../../../contracts/out");

/** Contracts with a generated module: name and the TS identifier prefix. */
export const GENERATED = [
  { name: "BitcoinFacts", ident: "bitcoinFacts", constant: "BITCOIN_FACTS" },
  { name: "PopFinality", ident: "popFinality", constant: "POP_FINALITY" },
  { name: "FidelityBonds", ident: "fidelityBonds", constant: "FIDELITY_BONDS" },
] as const;

interface ForgeArtifact {
  abi: unknown[];
  bytecode: { object: string };
  deployedBytecode: { object: string };
}

export function readArtifact(name: string): ForgeArtifact {
  return JSON.parse(readFileSync(join(CONTRACTS_OUT, `${name}.sol`, `${name}.json`), "utf8")) as ForgeArtifact;
}

export function renderAbiModule(c: (typeof GENERATED)[number], artifact: ForgeArtifact): string {
  const abi = JSON.stringify(artifact.abi, null, 2);
  return `// Generated by src/abi/generate.ts from contracts/out/${c.name}.sol/${c.name}.json (forge build, default
// profile: solc 0.8.28, cancun, 200 runs, no CBOR metadata). Do not edit: run \`npm run gen:abi\`.
// test/facts.test.ts fails when this file and the forge output differ.

export const ${c.ident}Abi = ${abi} as const;

/** Creation code. No constructor arguments, so this alone fixes the CREATE2 address. */
export const ${c.constant}_INIT_CODE = "${artifact.bytecode.object}" as const;

/** Runtime code, for placing the contract by eth_call state override where it is not deployed. */
export const ${c.constant}_RUNTIME = "${artifact.deployedBytecode.object}" as const;
`;
}

export function modulePath(c: (typeof GENERATED)[number]): string {
  return join(HERE, `${c.name}.ts`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  for (const c of GENERATED) {
    writeFileSync(modulePath(c), renderAbiModule(c, readArtifact(c.name)));
    process.stdout.write(`wrote ${modulePath(c)}\n`);
  }
}
